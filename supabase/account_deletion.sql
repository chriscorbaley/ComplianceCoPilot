-- ── Confirm ────────────────────────────────────────────────────────────────
-- Expect the seven deletion_requests columns.
select column_name, data_type, is_nullable
from information_schema.columns
where table_schema = 'public'
  and table_name = 'deletion_requests'
order by ordinal_position;

-- Expect 't' (RLS on) and 0 policies. Anything other than 0 is a security bug.
select relrowsecurity as rls_enabled,
       (select count(*) from pg_policies
         where schemaname = 'public' and tablename = 'deletion_requests') as policy_count
from pg_class
where oid = 'public.deletion_requests'::regclass;

-- Expect the widened list, including deletion_confirm + deletion_complete.
select pg_get_constraintdef(oid) as template_key_check
from pg_constraint
where conrelid = 'public.email_templates'::regclass
  and conname = 'email_templates_template_key_check';

-- Expect six rows. available_variables is printed raw rather than parsed: it
-- is TEXT here (see the note above), so jsonb_array_length() errors on it, and
-- because the whole file runs in one transaction that error would roll back
-- the table creation above along with it.
select template_key, subject, available_variables
from public.email_templates
order by template_key;
