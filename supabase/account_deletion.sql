-- ═══════════════════════════════════════════════════════════════════════════
-- Account deletion: deletion_requests + deletion email templates
-- ═══════════════════════════════════════════════════════════════════════════
-- Run in Supabase → SQL Editor. Idempotent: safe to re-run.
--
-- REQUIRED BY supabase/functions/delete-account/index.ts and by the web-based
-- deletion request page. Run this BEFORE deploying the deletion functions, or
-- the confirm flow has nowhere to record its tokens.
--
-- WHY THIS EXISTS
-- Apple Guideline 5.1.1(v) requires account deletion to be initiated IN the
-- app, and Google Play additionally requires a web-based deletion request page
-- reachable without installing the app. Those are two different trust models:
--
--   • IN-APP (immediate): the caller holds a valid authenticated JWT, so the
--     account is already proven and deletion runs straight away. Nothing in
--     this file is involved — delete-account reads the target from the JWT's
--     own `sub` claim.
--   • WEB (confirm-by-email): the requester is anonymous. Anyone could type
--     anyone's address, so the request only becomes actionable after the owner
--     of the mailbox clicks a one-time link. `deletion_requests` is that
--     pending state.
--
-- THE RESPONSE MUST NOT REVEAL WHETHER AN EMAIL IS REGISTERED
-- user_id is nullable on purpose. A request for an address with no account
-- still gets a row (with user_id null and no email sent), so the web page can
-- return exactly the same "check your inbox" response either way. Branching the
-- response on whether the account exists would turn the page into an account
-- enumeration oracle.
--
-- TOKENS ARE GENERATED BY THE FUNCTION, NOT BY POSTGRES
-- `token` has no default. The Edge Function mints it with
-- crypto.getRandomValues() and stores the result here. Postgres' gen_random_uuid()
-- is fine as a surrogate key but a UUIDv4 is not a secret to hand out in a URL —
-- it carries version/variant bits and is generated where the value is also
-- logged. Single-use is enforced by `consumed_at`, expiry by `expires_at`.
--
-- The seeded `deletion_confirm` copy states that the link expires in 24 hours,
-- so the sender must write `expires_at = now() + interval '24 hours'`. Change
-- both together or the email will lie.

create extension if not exists pgcrypto;

-- ─── deletion_requests ───────────────────────────────────────────────────────

create table if not exists public.deletion_requests (
  id uuid primary key default gen_random_uuid(),
  -- The address the request was made for, recorded even when it matches no
  -- account (see the enumeration note above).
  email text not null,
  -- Null when no account matched at request time. Cascades so a deleted
  -- account never leaves a live token pointing at it.
  user_id uuid references auth.users(id) on delete cascade,
  -- Securely random, minted by the Edge Function. Unique so a replayed insert
  -- can never silently shadow an existing pending request.
  token text not null unique,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null,
  -- Set the moment the token is redeemed. Non-null means spent: the confirm
  -- function must refuse it even if expires_at is still in the future.
  consumed_at timestamptz
);

comment on table public.deletion_requests is
  'Pending web-initiated account deletion requests. Service-role only: RLS is enabled with no policies, so every anon/authenticated client is denied.';
comment on column public.deletion_requests.user_id is
  'Null when the requested email matched no account. The row is still written so the web response cannot be used to enumerate registered addresses.';
comment on column public.deletion_requests.token is
  'Single-use confirmation secret, generated by the Edge Function with crypto.getRandomValues() (never by Postgres). Spent when consumed_at is set.';
comment on column public.deletion_requests.consumed_at is
  'Redemption timestamp. A non-null value permanently invalidates the token.';

-- Token lookup is the hot path (one read per confirmation click).
create index if not exists deletion_requests_token_idx
  on public.deletion_requests (token);

-- Supports both the "is there already a live request for this email" check and
-- the eventual cleanup of stale rows.
create index if not exists deletion_requests_pending_idx
  on public.deletion_requests (expires_at)
  where consumed_at is null;

create index if not exists deletion_requests_email_idx
  on public.deletion_requests (email, created_at desc);

-- ── Row level security ──────────────────────────────────────────────────────
-- Enabled with ZERO policies, and that is the entire access model: RLS with no
-- matching policy denies every operation to anon and authenticated, while the
-- service role bypasses RLS and is unaffected. Only the deletion Edge Functions
-- ever touch this table.
--
-- Do NOT add a policy here. A readable token is a deletable account: anyone who
-- could select a pending row could delete the account it points at, and anyone
-- who could insert one could forge a request. The drops below are defensive —
-- they remove any policy a previous experiment may have left behind, so
-- re-running this file always returns the table to "no policies".

alter table public.deletion_requests enable row level security;

drop policy if exists deletion_requests_select_own on public.deletion_requests;
drop policy if exists deletion_requests_insert_own on public.deletion_requests;
drop policy if exists deletion_requests_read on public.deletion_requests;

-- ═══════════════════════════════════════════════════════════════════════════
-- email_templates: allow the two account-deletion keys
-- ═══════════════════════════════════════════════════════════════════════════
-- template_key carries a CHECK constraint listing every permitted key, so a new
-- template cannot simply be inserted — the constraint has to be widened first.
--
-- The constraint's name is NOT assumed. It was created inline by
-- `check (template_key in (...))` inside a CREATE TABLE, so Postgres generated
-- the name, and it differs between environments that built the table at
-- different times (and from a re-run of this file). Look it up from the
-- catalog by what it constrains instead.

do $$
declare
  c record;
begin
  for c in
    select con.conname
    from pg_constraint con
    join pg_class rel on rel.oid = con.conrelid
    join pg_namespace nsp on nsp.oid = rel.relnamespace
    where nsp.nspname = 'public'
      and rel.relname = 'email_templates'
      -- 'c' is a CHECK constraint: this deliberately excludes the NOT NULL
      -- ('n' in PG17) and UNIQUE ('u') constraints on the same column.
      and con.contype = 'c'
      and pg_get_constraintdef(con.oid) ilike '%template_key%'
  loop
    execute format('alter table public.email_templates drop constraint %I;', c.conname);
    raise notice 'account_deletion.sql: dropped check constraint % on public.email_templates', c.conname;
  end loop;
end $$;

-- Recreated under a known, stable name. Because the loop above drops ANY check
-- constraint mentioning template_key — including this one — re-running the file
-- is safe.
alter table public.email_templates
  add constraint email_templates_template_key_check
  check (
    template_key in (
      'welcome',
      'verification',
      'deletion_warning',
      'cancellation_confirm',
      'deletion_confirm',
      'deletion_complete'
    )
  );

